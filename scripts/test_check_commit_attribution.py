#!/usr/bin/env python3
"""Attribution-gate fixtures (no git repository required)."""
from __future__ import annotations

import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import check_commit_attribution as gate

FIELD = gate.FIELD
RECORD = gate.RECORD
HOST = "Johnnys-M4-Pro.local"
OWNER_NAME = "Johnny Wang"
OWNER_EMAIL = "dehydratedflask@users.noreply.github.com"


class IdentityTests(unittest.TestCase):
    def test_owner_identity_is_clean(self):
        self.assertEqual(
            gate.identity_problems(OWNER_NAME, OWNER_EMAIL, HOST), []
        )

    def test_hostname_email_rejected(self):
        bad = gate.identity_problems(
            OWNER_NAME, "dehydratedflask@Johnnys-M4-Pro.local", HOST
        )
        self.assertTrue(bad)

    def test_bare_hostname_domain_rejected(self):
        bad = gate.identity_problems(
            OWNER_NAME, "dehydratedflask@Johnnys-M4-Pro", HOST
        )
        self.assertTrue(bad)

    def test_empty_email_rejected(self):
        # An unset user.email is the root cause of the 2026-10-22 leak.
        bad = gate.identity_problems(OWNER_NAME, "", HOST)
        self.assertTrue(any("empty" in p for p in bad), bad)

    def test_agent_name_rejected(self):
        for name in ("Claude Sonnet 5.5", "orchestrator", "Codex", "OpenCode"):
            with self.subTest(name=name):
                self.assertTrue(gate.identity_problems(name, OWNER_EMAIL, HOST))

    def test_anthropic_address_rejected(self):
        bad = gate.identity_problems(
            OWNER_NAME, "noreply@anthropic.com", HOST
        )
        self.assertTrue(bad)


class MessageTests(unittest.TestCase):
    def test_assistant_coauthor_trailer_rejected(self):
        message = (
            "feat(native): lift Init callee\n\n"
            "Co-Authored-By: Claude Sonnet 5.5 <noreply@anthropic.com>\n"
        )
        self.assertTrue(gate.message_problems(message))

    def test_human_coauthor_allowed(self):
        message = "feat: share helper\n\nCo-Authored-By: A Human <human@example.com>\n"
        self.assertEqual(gate.message_problems(message), [])

    def test_generated_with_claude_rejected(self):
        message = "feat: x\n\n🤖 Generated with [Claude Code](https://claude.com)\n"
        self.assertTrue(gate.message_problems(message))

    def test_robot_signoff_rejected(self):
        message = "feat: x\n\n🤖 generated by an agent\n"
        self.assertTrue(gate.message_problems(message))

    def test_message_discussing_attribution_allowed(self):
        # Docs/commits must be able to name the policy without failing the gate.
        message = (
            "docs: record why Claude attribution was removed from history\n\n"
            "The trailer cleanup is described in docs/ATTRIBUTION.md.\n"
        )
        self.assertEqual(gate.message_problems(message), [])


class ParseTests(unittest.TestCase):
    def test_parse_log_keeps_multiline_message(self):
        text = (
            f"abc123{FIELD}Johnny Wang{FIELD}{OWNER_EMAIL}"
            f"{FIELD}Johnny Wang{FIELD}{OWNER_EMAIL}{FIELD}subject\n\nbody\n{RECORD}"
        )
        commits = gate.parse_log(text)
        self.assertEqual(len(commits), 1)
        self.assertEqual(commits[0].sha, "abc123")
        self.assertIn("body", commits[0].message)

    def test_commit_problems_reports_author_and_message(self):
        commit = gate.Commit(
            sha="deadbeef" * 5,
            author_name="Claude",
            author_email="noreply@anthropic.com",
            committer_name=OWNER_NAME,
            committer_email=OWNER_EMAIL,
            message="feat: x\n\nCo-Authored-By: Claude <noreply@anthropic.com>\n",
        )
        problems = gate.commit_problems(commit)
        self.assertTrue(any("author" in p for p in problems), problems)
        self.assertTrue(any("trailer" in p for p in problems), problems)


if __name__ == "__main__":
    unittest.main()
