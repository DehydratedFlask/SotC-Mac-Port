#!/usr/bin/env python3
"""Generate the 0x2569d0 property table from private symbolic evidence.

Input: `local/re/evidence/owner-rows-2569d0/sym.json` (259 rows; hash-pinned by the report).
Output: `native/core/owner_properties_2569d0_table.inc.hpp`.

The output contains only recovered small integer/float constants, no game bytes. The two map-B
rodata cells are read from the pinned ELF by address and decoded here.
"""

from __future__ import annotations

import hashlib
import json
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SYM = ROOT / "local/re/evidence/owner-rows-2569d0/sym.json"
ELF = ROOT / "local/re/eboot.elf"
OUT = ROOT / "native/core/owner_properties_2569d0_table.inc.hpp"
ELF_SHA256 = "d0723afbdbd4cb3775c683a2b7f09534d371ce6d0b18146fc35b4d50c25861d3"

MAP_A_CALLEE = 11293280   # 0xac5260
MAP_B_CALLEE = 11293472   # 0xac5320

PATHS = {
    "mode1_gate1_head": "gate1_head",
    "mode1_gate0_head": "gate0_head",
    "mode1_tail": "tail",
    "final": "final",
    "mode2": "mode2",
}


def require(cond: bool, msg: str) -> None:
    if not cond:
        raise SystemExit(f"FAIL {msg}")


def read_qword(elf: bytes, rva: int) -> int:
    return struct.unpack_from("<Q", elf, 0x4000 + rva)[0]


def f32(bits: int) -> float:
    return struct.unpack("<f", struct.pack("<I", bits & 0xFFFFFFFF))[0]


def c_float(value: float) -> str:
    if value == 1.0:
        return "1.0f"
    if value == -1.0:
        return "-1.0f"
    return f"{value!r}f"


def main() -> int:
    elf = ELF.read_bytes()
    require(hashlib.sha256(elf).hexdigest() == ELF_SHA256, "unexpected ELF SHA256")
    rows = json.loads(SYM.read_text())
    require(len(rows) == 259, f"expected 259 rows, got {len(rows)}")

    tail_first = min(r["site"] for r in rows if r["region"] == "mode1_tail")
    out = []
    for row in rows:
        callee = row["callee"]
        path = PATHS[row["region"]]
        if callee == MAP_A_CALLEE:
            qword = row["rec"]["0"][1]
            tag = row["rec"]["8"][1]
            i = struct.unpack("<i", struct.pack("<I", qword & 0xFFFFFFFF))[0]
            f = f32(qword >> 32)
            out.append((row["key"], "A", path, i, f, tag, 0, 0.0, row["site"]))
        elif callee == MAP_B_CALLEE:
            rec0 = row["rec"].get("0")
            if rec0 is None:
                pair = read_qword(elf, 0xFC3360)
            elif rec0[0] == "global":
                pair = read_qword(elf, rec0[1])
            else:
                pair = rec0[1]
            rec8 = row["rec"]["8"]
            if rec8[0] == "imm":
                bits = rec8[1]
                v = f32(bits & 0xFFFFFFFF)
                tag = bits >> 32
            else:
                # Key 0x9b assembles rec8 as mov eax,0xbf800000; store qword => v=-1.0, tag=0.
                v = -1.0
                tag = 0
            out.append((row["key"], "B", path, 0, 0.0, tag, pair, v, row["site"]))
        else:
            raise SystemExit(f"unknown callee {callee}")

    # The first tail row is the gate0 pending key 0x1c; mark it separately and synthesize the
    # gate1 pending key 0x23 (its record comes from 0x2570fb, not a property site).
    patched = []
    for key, m, path, i, f, tag, pair, v, site in out:
        if site == tail_first and path == "tail":
            path = "gate0_pending"
        patched.append((key, m, path, i, f, tag, pair, v, site))
    patched.append((0x23, "A", "gate1_pending", 8, 1.0, 6, 0, 0.0, 0x2570FB))

    lines = [
        "// Generated by scripts/extract_owner_properties_2569d0.py from private sym.json.",
        "// Do not edit by hand. 259 recovered rows: 236 map A (0xac5260) + 23 map B (0xac5320).",
        "// path: 0 gate1_head, 1 gate0_head, 2 tail, 3 final, 4 mode2, 5 gate0_pending,",
        "//       6 gate1_pending. Map: 0 = A, 1 = B.",
        "#pragma once",
        "#include <cstdint>",
        "",
        "namespace sotc {",
        "namespace detail {",
        "struct OwnerPropertyRow {",
        "    std::uint16_t key;",
        "    std::uint8_t map;",
        "    std::uint8_t path;",
        "    std::int32_t i;",
        "    float f;",
        "    std::uint32_t tag;",
        "    std::uint64_t pair;",
        "    float v;",
        "};",
        "",
        "inline constexpr OwnerPropertyRow kOwnerProperties[] = {",
    ]
    path_index = {
        "gate1_head": 0,
        "gate0_head": 1,
        "tail": 2,
        "final": 3,
        "mode2": 4,
        "gate0_pending": 5,
        "gate1_pending": 6,
    }
    for key, m, path, i, f, tag, pair, v, _site in patched:
        lines.append(
            f"    {{{key:#06x}, {0 if m == 'A' else 1}, {path_index[path]}, {i}, "
            f"{c_float(f)}, {tag:#010x}, {pair:#018x}ULL, {c_float(v)}}},"
        )
    lines += [
        "};",
        "}  // namespace detail",
        "}  // namespace sotc",
        "",
    ]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT} ({len(patched)} rows)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
