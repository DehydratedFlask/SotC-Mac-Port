// Byte-exact fixture for original ctor RVA 0xee1130 (ctor index 21).
// The expected image is written as explicit literals, independent of the implementation's
// named constants; the ELF tie lives in tools/lift/check_fee1130.py.
#include <cstdio>
#include <cstdlib>
#include <cstring>

#include "core/const_table_ee1130.hpp"

#define CHECK(c) do { if (!(c)) { std::fprintf(stderr, "FAIL %s:%d %s\n", __FILE__, __LINE__, #c); std::exit(1); } } while (0)

using namespace sotc;

namespace {

constexpr std::uint8_t kExpected[0x80] = {
    // +0x00
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    // +0x08 rax = [0x1323b50]
    0x00, 0x00, 0x00, 0x00, 0xff, 0xff, 0xff, 0xff,
    // +0x10 xmm1 all-ones
    0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff,
    // +0x18
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    // +0x20 all-ones
    0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff,
    // +0x28 xmm2 = [0x1323bdc] = 0xffffffff zero-extended
    0xff, 0xff, 0xff, 0xff, 0x00, 0x00, 0x00, 0x00,
    // +0x30 rax again
    0x00, 0x00, 0x00, 0x00, 0xff, 0xff, 0xff, 0xff,
    // +0x38 all-ones
    0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff,
    // +0x40 xmm1 = [0x1323b60] (4 x 0x34000000)
    0x00, 0x00, 0x00, 0x34, 0x00, 0x00, 0x00, 0x34,
    0x00, 0x00, 0x00, 0x34, 0x00, 0x00, 0x00, 0x34,
    // +0x50 rdx = [0x1323b70] (two -1.0f)
    0x00, 0x00, 0x80, 0xbf, 0x00, 0x00, 0x80, 0xbf,
    // +0x58 rcx = [0x1323b80] (1.0f, -1.0f)
    0x00, 0x00, 0x80, 0xbf, 0x00, 0x00, 0x80, 0x3f,
    // +0x60
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    // +0x68 rdx = [0x1323b90] (FLT_MAX, 0)
    0x00, 0x00, 0x00, 0x00, 0xff, 0xff, 0x7f, 0x7f,
    // +0x70 rcx = [0x1323ba0] (two -FLT_MAX)
    0xff, 0xff, 0x7f, 0xff, 0xff, 0xff, 0x7f, 0xff,
    // +0x78 xmm0 = [0x1323be0] = 0xff7fffff zero-extended
    0xff, 0xff, 0x7f, 0xff, 0x00, 0x00, 0x00, 0x00,
};

}  // namespace

int main(int argc, char**) {
    ConstTableEe1130 table;
    table.fill(0xa5);
    init_const_table_ee1130(table);
    CHECK(std::memcmp(table.data(), kExpected, sizeof(kExpected)) == 0);

    // Idempotent: every byte is written unconditionally, so a dirty table is fully overwritten.
    for (auto& byte : table) byte = 0x5a;
    init_const_table_ee1130(table);
    CHECK(std::memcmp(table.data(), kExpected, sizeof(kExpected)) == 0);

    if (argc > 1) {
        std::printf("{\"length\":%zu,\"sha256_payload\":\"", table.size());
        for (std::size_t i = 0; i < table.size(); ++i) std::printf("%02x", table[i]);
        std::printf("\"}\n");
    } else {
        std::puts("const_table_ee1130: all checks passed");
    }
    return 0;
}
