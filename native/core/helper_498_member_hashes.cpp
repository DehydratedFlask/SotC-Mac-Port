bool member_hash_getter_498(std::uint32_t rva, std::uint32_t& value) noexcept {
    for (const MemberHashRecord498& r : kMemberHashRecords498) {
        if (rva == r.lo_getter_rva) { value = r.lo; return true; }
        if (rva == r.hi_getter_rva) { value = r.hi; return true; }
    }
    return false;
}

void fill_member_hash_cells_498(std::uint8_t (&cells)[kMemberHashCellsBytes498]) noexcept {
    for (std::size_t i = 0; i < kMemberHashRecordCount498; ++i) {
        const MemberHashRecord498& r = kMemberHashRecords498[i];
        std::uint8_t* cell = cells + i * kMemberHashRecordStride498;
        std::memcpy(cell + 0, &r.lo, 4);     // mov [cell+0], ebx   (ebx = lo getter result)
        std::memcpy(cell + 4, &r.hi, 4);     // mov [cell+4], eax   (eax = hi getter result)
        std::memcpy(cell + 8, &r.size, 4);   // mov dword [cell+8], size
    }
}

