def x_slot437_cells(e, spec) -> None:
    """Relational tie of the 16 view cells: element i = array + 0x20*i gets the i-th text, chunk k's atexit comes
    right after element 4k+3 and names destructor k, and destructor k releases exactly elements 4k+3, 4k+2, 4k, 4k+1
    (then the element-0 tail jump), so the native chunking (4 x 4) and the destructor <-> element pairing hold."""
    from slot_pin_util import require
    for i, site in enumerate(F2F0_SITES):
        require(e.call(site) == 0xF2F0, f"element {i}: call target 0xf2f0")
        require(e.rip(site - 16, 7, 3) == VIEW_ARRAY + 0x20 * i, f"element {i}: destination cell")
        require(e.rip(site - 9, 7, 3) == VIEW_TEXTS[i][0], f"element {i}: text address")
        require(e.read(site - 2, 2) == bytes.fromhex("31f6"), f"element {i}: ignored esi argument is zero")
    for k, site in enumerate(ATEXIT_SITES):
        require(site - F2F0_SITES[4 * k + 3] == 0x11, f"chunk {k}: atexit follows element {4 * k + 3}")
        require(e.call(site) == 0xF8F390, f"chunk {k}: __cxa_atexit")
        require(e.rip(site - 12, 7, 3) == CHUNK_DTORS[k], f"chunk {k}: destructor address")
        dtor = CHUNK_DTORS[k]
        cell = lambda n: VIEW_ARRAY + 0x20 * (4 * k + n)   # noqa: E731
        require(e.rip(dtor + 6, 7, 3) == cell(3), f"chunk {k}: destructor releases element {4 * k + 3} first")
        require(e.rip(dtor + 0x12, 7, 3) == cell(2), f"chunk {k}: destructor releases element {4 * k + 2}")
        require(e.rip(dtor + 0x19, 7, 3) == cell(0), f"chunk {k}: destructor holds element {4 * k} for the tail")
        require(e.rip(dtor + 0x25, 7, 3) == cell(1), f"chunk {k}: destructor releases element {4 * k + 1}")
        require(e.call(dtor + 0xD) == 0xF590 and e.call(dtor + 0x20) == 0xF590 and e.call(dtor + 0x2C) == 0xF590,
                f"chunk {k}: destructor release calls")
        require(e.jmp(dtor + 0x3A) == 0xF590, f"chunk {k}: element {4 * k} is released by the tail jump")


bp.lib.EXTRAS["slot437_cells"] = x_slot437_cells


