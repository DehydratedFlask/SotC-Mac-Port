def elf_extra(e) -> None:
    for rva, text in STRINGS:
        require(bytes(e.read(rva, len(text) + 1)) == text.encode() + b"\0", f"literal {rva:#x}")
    for rva, text, _ in CONNECTION_ROWS:
        require(bytes(e.read(rva, len(text) + 1)) == text.encode() + b"\0",
                f"connection row {rva:#x}")
    # Identity address points and the indirect-call slots.
    require(e.u64(0x15976A0 + 0x10) == 0x91210, "cell vtable slot 2")
    require(e.u64(0x1594208 + 0x10) == 0x20B0 and e.u64(0x1594208 + 0x20) == 0x20D60,
            "bool variable vtable dtor/register slots")
    require(e.u64(0x15940A0 + 0x20) == 0x20D60, "bool variable mid vtable register slot")
    require(e.u64(0x1594DC0 + 0x10) == 0x4B0 and e.u64(0x1594DC0 + 0x20) == 0x20D60,
            "command vtable dtor/register slots")
    require(e.u64(0x159ABC0 + 0x18) == 0x2111D0, "scratch bare-ret slot")
    # The 0x30-byte pose constant at 0xfab6b0: two float4 (1, 0, 0, 0) then four id words.
    pose = bytes(e.read(0xfab6b0, 0x30))
    require(pose == bytes.fromhex("0000803f000000000000000000000000"
                                  "0000803f000000000000000000000000"
                                  "0000803f000000000000000000000000"), "pose float words")
    ids = bytes(e.read(0xfab6e0, 0x10))
    require(ids == bytes.fromhex("68641bff16641bff0c641bff02641bff"), "pose id words")


