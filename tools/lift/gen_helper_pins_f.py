def pins_for(rva: int, size: int) -> list[tuple[int, str]]:
    text = subprocess.run(["/usr/bin/objdump", "-d", f"--start-address={rva:#x}", f"--stop-address={rva + size:#x}",
                           str(ELF)], capture_output=True, text=True, check=True).stdout
    rows: list[tuple[int, str]] = []
    for line in text.splitlines():
        match = re.match(r"^\s*([0-9a-f]+):\s+((?:[0-9a-f]{2}(?: |\t|$))+)\s*(\S.*)?$", line)
        if not match:
            continue
        addr = int(match.group(1), 16)
        raw = match.group(2).replace(" ", "")
        if match.group(3) is None or "\t" not in line:
            # continuation of the previous instruction's bytes
            if rows and match.group(3) is None:
                off, hexstr = rows[-1]
                rows[-1] = (off, hexstr + raw)
                continue
        rows.append((addr - rva, raw))
    assert sum(len(h) // 2 for _, h in rows) == size, (hex(rva), size, sum(len(h) // 2 for _, h in rows))
    return rows


def main() -> int:
    parts = ['"""Instruction-level byte pins for tools/lift/check_helper_*.py of CPU-01-SLOT408-PREREQS.',
             'GENERATED by tools/lift/gen_helper_pins_f.py from `objdump -d` of the pinned private ELF bodies; offsets',
             'are relative to each body\'s first byte. DATA ONLY; a changed byte is a failed check."""', "",
             "PINS: dict[str, list[tuple[int, str]]] = {"]
    for key, rva, size, label in BODIES:
        parts.append(f'    "{key}": [  # {label}, {size:#x} B')
        for off, hexstr in pins_for(rva, size):
            parts.append(f'        ({off:#x}, "{hexstr}"),')
        parts.append("    ],")
    parts.append("}")
    text = "\n".join(parts) + "\n"
    if "--write" in sys.argv:
        OUT.write_text(text)
        print(f"wrote {OUT}")
    else:
        sys.stdout.write(text)
    return 0


