def elf_extra(e) -> None:
    for rva, text in STRINGS:
        e.cstring(rva, text)
    for rva, blob in BLOBS:
        e.bytes_at(rva, blob.hex(), 'prefix blob')
    # The scratch vtable's eight words: four code slots, two zero, two data tags.
    for slot, want in enumerate((0x16A5A0, 0x16A5B0, 0x16A5C0, 0x16A5D0, 0, 0, 0x16F550, 0x16F720)):
        require(e.u64(0x1598780 + 8 * slot) == want, f"scratch vtable slot {slot}")
    require(e.u64(0x1594DD0) == 0x4B0, "command vtable slot 0")
    require(e.u64(0x1594DE0) == 0x20D60, "command vtable slot 2")
    require(e.u64(0x15FE5E0) == 0x1990, "invoker thunk cell")
    require(e.u64(0x1604218) == 0x1604218, "dso handle cell")


