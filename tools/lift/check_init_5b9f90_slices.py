#!/usr/bin/env python3
'''ELF-tie the native 0x5b9f90 slice model and its slice map.

Private: needs local/re/eboot.elf. Pins the body extent and its single exit/loop, the ten slice
boundaries, the three group call sites, and every one of the 32 command tuples in the two executed
pages: call target, caption and command string RVAs and lengths, the target tag lea, and the 0x30
flags store.

The native model is native/core/init_5b9f90_slices.cpp; the map is docs/5B9F90_SLICES.md,
regenerated by tools/lift/slice_5b9f90.py.
'''

from __future__ import annotations

import hashlib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'scripts'))
sys.path.insert(0, str(ROOT / 'tools/lift'))
import ps4_dynlink as d  # noqa: E402
import slice_5b9f90 as smap  # noqa: E402

ELF_SHA256 = 'd0723afbdbd4cb3775c683a2b7f09534d371ce6d0b18146fc35b4d50c25861d3'
BODY = 0x5B9F90
BODY_END = 0x5C56B1          # exclusive
BODY_SIZE = 0xB721           # 46,881
RET_RVA = 0x5C56AA
LOOP_HEAD = 0x5C1D50
LOOP_EDGE = 0x5C1E5B
GROUP_CTOR = 0x26C10
COMMAND_CTOR = 0x26F90
PAGE_BUILDERS = (0x2170, 0x5CF140)
RARE = (0x2170, 0x5CF140, 0x5DBF40, 0x7F8930, 0x5C94B0, 0xB25840)
FLAGS_STORE = bytes.fromhex('b930000000')     # movl $0x30,%ecx
FLAGS_STORE_R9 = bytes.fromhex('41b930000000')  # movl $0x30,%r9d

HEADER = ROOT / 'native/core/init_5b9f90_slices.hpp'

SLICE_RE = re.compile(r'\{"(S\d)", 0x([0-9A-F]+), 0x([0-9A-F]+), (\d+), (\d+), '
                      r'Init5b9f90SliceStatus::(\w+),')
PAGE_RE = re.compile(r'\{"(S3\.\d)", "([^"]*)", (\d+), "([^"]*)", (\d+), '
                     r'0x([0-9A-F]+), 0x([0-9A-F]+), 0x([0-9A-F]+), (\d+),')
ITEM_RE = re.compile(r'\{"([^"]*)", (\d+), "([^"]*)", (\d+), 0x([0-9A-F]+), 0x([0-9A-F]+)\},')


def require(cond, what):
    if not cond:
        raise SystemExit('FAIL check_init_5b9f90_slices: ' + what)


def read_cstr(img, va):
    '''NUL-terminated text, or None when the address is not file-backed (e.g. a .bss tag).'''
    out = bytearray()
    for i in range(256):
        try:
            b = img.read(va + i, 1)
        except ValueError:
            return None
        if b == b'\x00':
            break
        out += b
    return out.decode('latin-1')


def parse_header():
    text = HEADER.read_text()
    slices = [(m.group(1), int(m.group(2), 16), int(m.group(3), 16), int(m.group(4)),
               int(m.group(5)), m.group(6)) for m in SLICE_RE.finditer(text)]
    pages = [(m.group(1), m.group(2), int(m.group(3)), m.group(4), int(m.group(5)),
              int(m.group(6), 16), int(m.group(7), 16), int(m.group(8), 16), int(m.group(9)))
             for m in PAGE_RE.finditer(text)]
    items = [(m.group(1), int(m.group(2)), m.group(3), int(m.group(4)), int(m.group(5), 16),
              int(m.group(6), 16)) for m in ITEM_RE.finditer(text)]
    return slices, pages, items


def main() -> int:
    data = (ROOT / 'local/re/eboot.elf').read_bytes()
    sha = hashlib.sha256(data).hexdigest()
    require(sha == ELF_SHA256, 'ELF sha256 ' + sha)
    _, headers = d.program_headers(data)
    img = d.Image(data, headers)

    require(img.read(BODY, 1) == b'\x55', 'body starts with pushq %rbp')
    require(img.read(RET_RVA, 1) == b'\xc3', 'single ret at 0x5c56aa')
    require(read_cstr(img, 0x1266E06) == 'CP10', 'S0 parent literal')
    require(read_cstr(img, 0x1266E0B) == 'Shadow', 'S0 caption literal')
    require(read_cstr(img, 0x1266E12) == 'Shadow Boss Jump', 'S3.1 page literal')
    require(read_cstr(img, 0x1266F90) == 'Shadow Boss Outro Jump', 'S3.2 page literal')

    instructions = [(a, m, o, raw) for a, m, o, raw in smap.disassemble() if a < BODY_END]
    by_addr = {a: (m, o) for a, m, o, _ in instructions}
    require(len(instructions) == 7645, 'instruction count ' + str(len(instructions)))

    rets = [a for a, m, _, _ in instructions if m.startswith('ret')]
    require(rets == [RET_RVA], 'exactly one ret: ' + str([hex(a) for a in rets]))

    backwards = []
    for addr, mnemonic, operands, _ in instructions:
        if not mnemonic.startswith('j'):
            continue
        m = re.search(r'^0x([0-9a-f]+)', operands)
        if m and int(m.group(1), 16) < addr:
            backwards.append((addr, int(m.group(1), 16)))
    require(backwards == [(LOOP_EDGE, LOOP_HEAD)],
            'single backward branch: ' + str([(hex(a), hex(t)) for a, t in backwards]))

    calls = []
    for addr, mnemonic, operands, raw in instructions:
        if mnemonic != 'callq' or not operands.startswith('0x'):
            continue
        calls.append((addr, int(operands.split()[0], 16)))
    require(len(calls) == 1136, 'direct call count ' + str(len(calls)))

    # Slice boundaries are exactly the rare-callee call sites and the loop head/exit.
    expected_starts = [BODY, 0x5BA041, 0x5BA046, 0x5BA04B, 0x5BC3D4, 0x5BC3DE,
                       0x5C1196, 0x5C11A0, LOOP_HEAD, 0x5C1E61]
    slice_table, pages, items = parse_header()
    require(len(slice_table) == 10, 'ten slices')
    require([s[1] for s in slice_table] == expected_starts,
            'slice starts ' + str([hex(s[1]) for s in slice_table]))
    require(slice_table[-1][2] == BODY_END, 'last slice ends at the body end')
    for i in range(len(slice_table) - 1):
        require(slice_table[i][2] == slice_table[i + 1][1], 'slice ' + slice_table[i][0] + ' is contiguous')
    require(sum(s[2] - s[1] for s in slice_table) == BODY_SIZE, 'slice sizes sum to 46,881')
    for sid, start, end, count, ncalls, status in slice_table:
        measured = [1 for a, *_ in instructions if start <= a < end]
        got = sum(measured)
        require(got == count, sid + ' instruction count ' + str(got) + ' != ' + str(count))
        region_calls = [t for a, t in calls if start <= a < end]
        require(len(region_calls) == ncalls, sid + ' call count')
        if status == 'contract':
            require(region_calls and region_calls[0] in PAGE_BUILDERS,
                    sid + ' contract names a page builder')
        if sid in ('S0', 'S3.1', 'S3.2') or status == 'executed':
            pass
    require([s[0] for s in slice_table if s[5] == 'executed'] == ['S0'],
            'executed coarse slices')
    require([s[0] for s in slice_table if s[5] == 'partial'] == ['S3'],
            'S3 is the only partial coarse slice')

    # Page table: group site is a 0x26c10 call and both views appear as lea targets.
    require([p[0] for p in pages] == ['S3.1', 'S3.2', 'S3.3', 'S3.4', 'S3.5', 'S3.6'], 'six S3 pages')
    for pid, parent, plen, caption, clen, start, end, group_site, item_count in pages:
        require(by_addr.get(group_site, ('',))[0] == 'callq', pid + ' group site is a call')
        require(call_target_ok(img, group_site, GROUP_CTOR), pid + ' group ctor target')
        window = [(a, o) for a, m, o, _ in instructions if group_site - 0x80 <= a < group_site]
        targets = set()
        for _, o in window:
            targets.update(lee_targets(o))
        require(any(read_cstr(img, va) == caption for va in targets), pid + ' caption lea')
        require(start >= 0x5BA04B and end <= 0x5BC3D4, pid + ' inside S3')
        require(len(parent) == plen and len(caption) == clen, pid + ' view lengths')
        got = len([1 for a, t in calls if start <= a < end and t == COMMAND_CTOR])
        require(got == item_count, pid + ' item count ' + str(got) + ' != ' + str(item_count))

    # Page chain: S3.1/S3.2 hang under the S0 group "Shadow", S3.3 under "CP10".
    require(pages[0][1] == 'Shadow' and pages[1][1] == 'Shadow', 'boss pages under "Shadow"')
    require(pages[2][1] == 'CP10', '"Shadow Cheat" under "CP10"')

    # Item tuples: 32 command items across the two executed pages, each byte-pinned.
    require(len(items) == 32, '32 command items in the table')
    targets = [it[5] for it in items]
    require(len(set(targets)) == 32, 'unique item sites')
    for caption, clen, command, cmdlen, target_rva, site in items:
        require(len(caption) == clen, 'caption length at ' + hex(site))
        require(len(command) == cmdlen, 'command length at ' + hex(site))
        require(by_addr.get(site, ('',))[0] == 'callq', 'callq at ' + hex(site))
        require(call_target_ok(img, site, COMMAND_CTOR), '0x26f90 target at ' + hex(site))
        window = [(a, o, raw) for a, m, o, raw in instructions if site - 0x90 <= a < site]
        leas = set()
        for _, o, _ in window:
            leas.update(lee_targets(o))
        require(any(read_cstr(img, va) == caption for va in leas),
                'caption literal not referenced at ' + hex(site) + ': ' + caption)
        require(any(read_cstr(img, va) == command for va in leas),
                'command literal not referenced at ' + hex(site) + ': ' + command)
        page = next(p for p in pages if p[5] <= site < p[6])
        page_leas = set()
        for a, _m, o, _raw in instructions:
            if page[5] <= a < page[6]:
                page_leas.update(lee_targets(o))
        require(target_rva in page_leas,
                'target tag 0x%x not lea-ed in %s' % (target_rva, page[0]))
        blob = b''.join(bytes.fromhex(raw) for _, _, raw in window)
        require(FLAGS_STORE in blob or FLAGS_STORE_R9 in blob, 'flags 0x30 store at ' + hex(site))

    print('OK check_init_5b9f90_slices: sha=' + sha[:12] + '... size=' + str(BODY_SIZE) +
          ' insns=7645 ret=0x5c56aa loop=' + hex(LOOP_HEAD) + '<-' + hex(LOOP_EDGE) +
          ' slices=10 pages=6 items=32')
    return 0


def lee_targets(operands: str) -> list[int]:
    '''Every `# 0x...` comment on a lea line is a resolved rip-relative target.'''
    out = []
    m = re.search(r'#\s*0x([0-9a-f]+)', operands)
    if m:
        out.append(int(m.group(1), 16))
    return out


def call_target_ok(img, site: int, expected: int) -> bool:
    raw = img.read(site, 5)
    if raw[0] != 0xE8:
        return False
    rel = int.from_bytes(raw[1:5], 'little', signed=True)
    return (site + 5 + rel) & 0xFFFFFFFFFFFFFFFF == expected


if __name__ == '__main__':
    raise SystemExit(main())
