#!/usr/bin/env python3
"""Generator for tools/lift/helper_callee_pins_d.py (CPU-01-HELPER-CALLEE-MODELS-03).

Offline and read-only: runs `objdump -d` over the pinned private ELF and records one (offset, hex) pin per decoded
instruction for each listed body. DATA ONLY; the checkers decide what a pin means. A changed byte is a failed check,
never a silent update: regenerate only after re-reading the disassembly.

Usage: python3 -I tools/lift/gen_helper_pins_d.py [--write]
"""
from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ELF = ROOT / "local/re/eboot.elf"
OUT = ROOT / "tools/lift/helper_callee_pins_d.py"

# key, rva, size (FDE length), human label
BODIES = [
    ("store_one_8d650", 0x8D650, 7, "0x8d650 dword store of 1"),
    ("plt_strncpy_f8f630", 0xF8F630, 6, "0xf8f630 PLT thunk (jmp [GOT])"),
    ("record_ctor_a81700", 0xA81700, 190, "0xa81700 named record ctor + registry push"),
    ("registry_push_a81840", 0xA81840, 265, "0xa81840 push the record into the two vectors"),
    ("vec_reserve_a82050", 0xA82050, 245, "0xa82050 vector<T*> reserve(n)"),
    ("registry_ctor_a81b50", 0xA81B50, 34, "0xa81b50 registry zeroing ctor"),
    ("node_ref_56b4b0", 0x56B4B0, 138, "0x56b4b0 node reference builder"),
]


def pins_for(rva: int, size: int) -> list[tuple[int, str]]:
    text = subprocess.run(["/usr/bin/objdump", "-d", f"--start-address={rva:#x}", f"--stop-address={rva + size:#x}",
                           str(ELF)], capture_output=True, text=True, check=True).stdout
    rows: list[tuple[int, str]] = []
    for line in text.splitlines():
        match = re.match(r"^\s*([0-9a-f]+):\s+((?:[0-9a-f]{2}(?: |\t|$))+)\s*(\S.*)?$", line)
        if not match:
            continue
        addr = int(match.group(1), 16)
        raw = match.group(2).replace(" ", "")
        if match.group(3) is None or "\t" not in line:
            # continuation of the previous instruction's bytes
            if rows and match.group(3) is None:
                off, hexstr = rows[-1]
                rows[-1] = (off, hexstr + raw)
                continue
        rows.append((addr - rva, raw))
    assert sum(len(h) // 2 for _, h in rows) == size, (hex(rva), size, sum(len(h) // 2 for _, h in rows))
    return rows


def main() -> int:
    parts = ['"""Instruction-level byte pins for tools/lift/check_helper_*.py of CPU-01-HELPER-CALLEE-MODELS-03.',
             'GENERATED by tools/lift/gen_helper_pins_d.py from `objdump -d` of the pinned private ELF bodies; offsets',
             'are relative to each body\'s first byte. DATA ONLY; a changed byte is a failed check."""', "",
             "PINS: dict[str, list[tuple[int, str]]] = {"]
    for key, rva, size, label in BODIES:
        parts.append(f'    "{key}": [  # {label}, {size:#x} B')
        for off, hexstr in pins_for(rva, size):
            parts.append(f'        ({off:#x}, "{hexstr}"),')
        parts.append("    ],")
    parts.append("}")
    text = "\n".join(parts) + "\n"
    if "--write" in sys.argv:
        OUT.write_text(text)
        print(f"wrote {OUT}")
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
